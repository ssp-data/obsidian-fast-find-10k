import esbuild from 'esbuild';
import process from 'node:process';
import { copyFile, mkdir } from 'node:fs/promises';
import { builtinModules } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

/** Bundles src/worker.ts (with the wasm inlined as bytes) and returns its source text. */
export async function buildWorker({ prod = false } = {}) {
	const result = await esbuild.build({
		absWorkingDir: here,
		entryPoints: ['src/worker.ts'],
		bundle: true,
		format: 'iife',
		target: 'es2022',
		loader: { '.wasm': 'binary' },
		// wasm-bindgen's default-URL fallback; never taken because init gets the bytes.
		define: { 'import.meta.url': '"about:blank"' },
		sourcemap: prod ? false : 'inline',
		write: false,
		logLevel: 'warning',
	});
	return result.outputFiles[0].text;
}

/** Resolves `virtual:worker-source` to a fresh worker bundle on every (re)build. */
const workerSourcePlugin = (prod) => ({
	name: 'worker-source',
	setup(build) {
		build.onResolve({ filter: /^virtual:worker-source$/ }, (args) => ({ path: args.path, namespace: 'worker-source' }));
		build.onLoad({ filter: /.*/, namespace: 'worker-source' }, async () => ({
			contents: `export default ${JSON.stringify(await buildWorker({ prod }))};`,
			loader: 'js',
			watchFiles: [path.join(here, 'src/worker.ts'), path.join(here, 'src/protocol.ts'), path.join(here, '../crates/ff10k-wasm/pkg/ff10k_wasm.js'), path.join(here, '../crates/ff10k-wasm/pkg/ff10k_wasm_bg.wasm')],
		}));
	},
});

const copyStatic = {
	name: 'copy-static',
	setup(build) {
		build.onEnd(async () => {
			await mkdir(path.join(here, 'dist'), { recursive: true });
			for (const f of ['manifest.json', 'styles.css']) await copyFile(path.join(here, f), path.join(here, 'dist', f));
		});
	},
};

async function main() {
	const prod = process.argv[2] === 'production';
	const context = await esbuild.context({
		absWorkingDir: here,
		banner: { js: banner },
		entryPoints: ['src/main.ts'],
		bundle: true,
		external: [
			'obsidian',
			'electron',
			'@codemirror/autocomplete',
			'@codemirror/collab',
			'@codemirror/commands',
			'@codemirror/language',
			'@codemirror/lint',
			'@codemirror/search',
			'@codemirror/state',
			'@codemirror/view',
			'@lezer/common',
			'@lezer/highlight',
			'@lezer/lr',
			...builtinModules,
		],
		format: 'cjs',
		target: 'es2022',
		logLevel: 'info',
		sourcemap: prod ? false : 'inline',
		treeShaking: true,
		outfile: 'dist/main.js',
		minify: false,
		plugins: [workerSourcePlugin(prod), copyStatic],
	});
	if (prod) {
		await context.rebuild();
		await context.dispose();
	} else {
		await context.watch();
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
